import assert from "node:assert/strict";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const root = fileURLToPath(new URL("../", import.meta.url));
const license = await readFile(new URL("../node_modules/three/LICENSE", import.meta.url), "utf8");
const result = await build({
  root,
  configFile: false,
  logLevel: "warn",
  oxc: {
    jsx: { runtime: "classic" },
    jsxInject: 'import * as React from "react";',
  },
  define: { "process.env.NODE_ENV": JSON.stringify("production") },
  plugins: [{
    name: "lms-inline-styles",
    enforce: "pre",
    transform(code, id) {
      if (id.replaceAll("\\", "/").endsWith("/src/games/bridge-master/BridgeMaster.jsx")) {
        // The LMS entry embeds this same stylesheet as a string in a React style tag.
        const cssImport = 'import "./styles/bridge-master.css";';
        assert(code.includes(cssImport), "Update the exporter if the game CSS import changes");
        return { code: code.replace(cssImport, ""), map: null };
      }
    },
  }],
  build: {
    write: false,
    minify: false,
    sourcemap: false,
    target: "es2022",
    lib: { entry: "src/lms/entry.jsx", formats: ["es"] },
    rolldownOptions: {
      external: ["react"],
      output: { codeSplitting: false },
    },
  },
});
const outputs = Array.isArray(result) ? result : [result];
assert.equal(outputs.length, 1);
assert("output" in outputs[0]);
assert.equal(outputs[0].output.length, 1, "JSX must not require CSS, chunks, maps or other assets");
const chunk = outputs[0].output[0];
assert.equal(chunk.type, "chunk");
assert(chunk.imports.every((id) => id === "react"));
assert.equal(chunk.dynamicImports.length, 0);
const banner = `/*
Bridge Master — complete single-file LMS component, contract v1.
Generated by npm run export:lms. Edit project source and regenerate for updates.
Host supplies React 19; CSS, all levels, Three.js and game logic are embedded.
Mount the default export in an isolated iframe; see LMS-INTEGRATION.md.

Embedded Three.js license:
${license.trim()}
*/\n`;
await mkdir(new URL("../delivery/", import.meta.url), { recursive: true });
await writeFile(new URL("../delivery/BridgeMaster.jsx", import.meta.url), banner + chunk.code, "utf8");
console.log("Created delivery/BridgeMaster.jsx");
