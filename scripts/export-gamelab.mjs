import assert from "node:assert/strict";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { build } from "vite";
import { createManifest } from "../src/gamelab/manifest.js";

// Builds delivery/gamelab/Game.jsx: one UTF-8 file, `react` as the only import (GameLab contract §3).
const root = fileURLToPath(new URL("../", import.meta.url));
const license = await readFile(new URL("../node_modules/three/LICENSE", import.meta.url), "utf8");
const levelDirectory = new URL("../src/games/bridge-master/levels/", import.meta.url);
const levelFiles = (await readdir(levelDirectory)).filter((n) => /^bridge-\d+\.json$/.test(n)).sort();
const levelIds = await Promise.all(
  levelFiles.map(async (n) => JSON.parse(await readFile(new URL(n, levelDirectory), "utf8")).id),
);
const result = await build({
  root,
  configFile: false,
  logLevel: "warn",
  oxc: { jsx: { runtime: "classic" }, jsxInject: 'import * as React from "react";' },
  define: { "process.env.NODE_ENV": JSON.stringify("production") },
  plugins: [
    {
      name: "gamelab-inline-styles",
      enforce: "pre",
      transform(code, id) {
        if (id.replaceAll("\\", "/").endsWith("/src/games/bridge-master/BridgeMaster.jsx")) {
          // src/gamelab/Game.jsx embeds this same stylesheet in a <style> element; page-reset.css is never included.
          const cssImport = 'import "./styles/bridge-master.css";';
          assert(code.includes(cssImport), "Update the exporter if the game CSS import changes");
          return { code: code.replace(cssImport, ""), map: null };
        }
      },
    },
  ],
  build: {
    write: false,
    minify: false,
    sourcemap: false,
    target: "es2022",
    lib: { entry: "src/gamelab/Game.jsx", formats: ["es"] },
    rolldownOptions: { external: ["react"], output: { codeSplitting: false } },
  },
});
const outputs = Array.isArray(result) ? result : [result];
assert.equal(outputs.length, 1);
assert("output" in outputs[0]);
assert.equal(outputs[0].output.length, 1, "JSX must not require CSS, chunks, maps or other assets");
const chunk = outputs[0].output[0];
assert.equal(chunk.type, "chunk");
assert(chunk.imports.every((id) => id === "react"));
assert.equal(chunk.dynamicImports.length, 0);
const banner = `// @junior-gamecenter v1
/*
Bridge Master — GameLab JSX game, contract v1 (GameLab-JSX-AUTHOR-CONTRACT.md).
Generated by npm run export:gamelab. Edit the project source and regenerate for updates.
The host provides React and ReactDOM; CSS, all levels, Three.js and game logic are embedded.

Embedded Three.js license:
${license.trim()}
*/\n`;
// The manifest is a plain literal export (§4), generated from the real level list.
const manifest = `\nexport const gameCenterManifest = ${JSON.stringify(createManifest(levelIds), null, 2)};\n`;
const target = new URL("../delivery/gamelab/", import.meta.url);
await mkdir(target, { recursive: true });
await writeFile(new URL("Game.jsx", target), banner + chunk.code + manifest, "utf8");
console.log("Created delivery/gamelab/Game.jsx");
