// One-off helper: shrinks GameLab design-package 3D PNGs into inline WebP data URIs
// for the intro dialog. Run: node scripts/make-intro-assets.mjs
// Source images live in the parent GameLab repo (source/GameLab_Final_Design_Package).
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";

const assetDir = fileURLToPath(
  new URL("../../source/GameLab_Final_Design_Package/05_Assets/3D/", import.meta.url),
);
const jobs = [
  ["robotWave", "robot_wave.png", 340],
  ["coinStar", "coin_star.png", 128],
  ["purpleGem", "purple_gem.png", 120],
  ["trophy", "trophy.png", 140],
];
const browser = await chromium.launch({ channel: "chrome" });
const page = await browser.newPage();
const lines = ["// Generated by scripts/make-intro-assets.mjs from the GameLab design package. Do not edit."];
for (const [name, file, width] of jobs) {
  const png = (await readFile(assetDir + file)).toString("base64");
  const uri = await page.evaluate(
    async ({ png, width }) => {
      const image = new Image();
      image.src = `data:image/png;base64,${png}`;
      await image.decode();
      const canvas = document.createElement("canvas");
      canvas.width = width;
      canvas.height = Math.round((image.naturalHeight / image.naturalWidth) * width);
      const context = canvas.getContext("2d");
      context.imageSmoothingQuality = "high";
      context.drawImage(image, 0, 0, canvas.width, canvas.height);
      return canvas.toDataURL("image/webp", 0.86);
    },
    { png, width },
  );
  console.log(`${name}: ${(uri.length / 1024).toFixed(1)} kB`);
  lines.push(`export const ${name} = "${uri}";`);
}
await browser.close();
const target = new URL("../src/games/bridge-master/assets/", import.meta.url);
await mkdir(target, { recursive: true });
await writeFile(new URL("introAssets.js", target), lines.join("\n") + "\n", "utf8");
